package com.transvidcloud.backend.common.logging;

import static org.assertj.core.api.Assertions.assertThat;

import com.transvidcloud.backend.auth.dto.LoginRequest;
import java.util.UUID;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.system.CapturedOutput;
import org.springframework.boot.test.system.OutputCaptureExtension;
import org.springframework.boot.test.web.client.TestRestTemplate;
import org.springframework.http.HttpEntity;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpMethod;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertySource;
import org.testcontainers.containers.localstack.LocalStackContainer;
import org.testcontainers.utility.DockerImageName;

@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@ActiveProfiles("test")
@ExtendWith(OutputCaptureExtension.class)
@DisplayName("ObservabilityLoggingIT - Kiểm thử tích hợp khả năng quan sát & bảo mật log")
class ObservabilityLoggingIT {

    static LocalStackContainer localStack = new LocalStackContainer(DockerImageName.parse("localstack/localstack:3.0"))
            .withServices(
                    LocalStackContainer.Service.DYNAMODB,
                    LocalStackContainer.Service.S3,
                    LocalStackContainer.Service.SQS
            );

    static {
        localStack.start();
    }

    @DynamicPropertySource
    static void configureProperties(org.springframework.test.context.DynamicPropertyRegistry registry) {
        registry.add("tvc.aws.endpoint", () -> localStack.getEndpoint().toString());
        registry.add("spring.cloud.aws.region.static", () -> localStack.getRegion());
        registry.add("spring.cloud.aws.credentials.access-key", () -> localStack.getAccessKey());
        registry.add("spring.cloud.aws.credentials.secret-key", () -> localStack.getSecretKey());
    }

    @Autowired
    private TestRestTemplate restTemplate;

    @Test
    @DisplayName("US1: Tự động sinh correlationId và trả về trong header X-Correlation-ID khi client không truyền")
    void testAutoGeneratedCorrelationId(CapturedOutput output) {
        ResponseEntity<String> response = restTemplate.getForEntity("/actuator/health", String.class);

        assertThat(response.getStatusCode().is2xxSuccessful()).isTrue();
        String correlationHeader = response.getHeaders().getFirst("X-Correlation-ID");
        assertThat(correlationHeader).isNotBlank();
        UUID.fromString(correlationHeader); // Phải là UUID hợp lệ
    }

    @Test
    @DisplayName("US1: Tiếp nhận và truyền tải header X-Correlation-ID tùy biến từ client vào log và response")
    void testCustomCorrelationIdPropagation(CapturedOutput output) {
        String customId = "trace-test-client-998877";
        HttpHeaders headers = new HttpHeaders();
        headers.set("X-Correlation-ID", customId);
        HttpEntity<Void> request = new HttpEntity<>(headers);

        ResponseEntity<String> response = restTemplate.exchange("/actuator/health", HttpMethod.GET, request, String.class);

        assertThat(response.getStatusCode().is2xxSuccessful()).isTrue();
        assertThat(response.getHeaders().getFirst("X-Correlation-ID")).isEqualTo(customId);
    }

    @Test
    @DisplayName("US2: Bảo mật Log: Không làm rò rỉ mật khẩu bản rõ khi người dùng đăng nhập")
    void testPasswordMaskingDuringAuthentication(CapturedOutput output) {
        LoginRequest loginRequest = new LoginRequest("user_test_logging@transvidcloud.com", "SecretP@ssword12345");
        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        HttpEntity<LoginRequest> request = new HttpEntity<>(loginRequest, headers);

        // Gọi endpoint đăng nhập (kể cả thất bại do user chưa tồn tại)
        restTemplate.exchange("/auth/login", HttpMethod.POST, request, String.class);

        // Khẳng định mật khẩu bản rõ tuyệt đối không xuất hiện trong log stream
        assertThat(output.getAll()).doesNotContain("SecretP@ssword12345");
    }
}
